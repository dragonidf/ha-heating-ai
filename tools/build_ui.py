"""Bundle the frontend into Python so HACS AppDaemon downloads every asset."""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(check=False):
    version = (ROOT/'VERSION').read_text().strip()
    source = (ROOT/'frontend/heating-panel.js').read_text()
    sys.path.insert(0,str(ROOT/'apps/heating_ai'))
    from heating_ui import system_fields
    from heating_model import DEFAULT_MODEL
    schema=[{k:v for k,v in field.items() if k!='value'} for field in system_fields({},DEFAULT_MODEL)]
    pattern=r'/\* settings-schema:start \*/.*?/\* settings-schema:end \*/'
    block='/* settings-schema:start */\nconst SYSTEM_SCHEMA = '+json.dumps(schema,ensure_ascii=False,separators=(',',':'))+';\n/* settings-schema:end */'
    if not re.search(pattern,source,re.S):raise SystemExit('Missing static settings schema marker')
    rendered=re.sub(pattern,lambda match:block,source,flags=re.S)
    if rendered!=source:
        if check:raise SystemExit('Run python tools/build_ui.py to refresh the static settings schema')
        (ROOT/'frontend/heating-panel.js').write_text(rendered);source=rendered
    if f"const VERSION = '{version}';" not in source:
        raise SystemExit('Frontend VERSION does not match VERSION')
    digest = hashlib.sha256(source.encode()).hexdigest()[:16]
    content = ('# Generated by tools/build_ui.py; edit frontend/heating-panel.js instead.\n'
               f'VERSION = {version!r}\nDIGEST = {digest!r}\nSOURCE = {source!r}\n')
    target = ROOT/'apps/heating_ai/heating_ui_assets.py'
    if check:
        if not target.exists() or target.read_text() != content:
            actual=target.read_text() if target.exists() else ''
            diff=next((i for i,(a,b) in enumerate(zip(actual,content)) if a!=b),min(len(actual),len(content)))
            print("DEBUG ui target_match=False expected_digest="+digest+" lengths="+str((len(content),len(actual)))+" diff="+str(diff)+" expected="+repr(content[diff:diff+80])+" actual="+repr(actual[diff:diff+80]))
            raise SystemExit('Run python tools/build_ui.py and commit the generated assets')
    else:
        target.write_text(content)
    modules={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(target.parent.glob('heating_*.py'))}
    manifest=json.dumps(dict(version=version,module_hashes=modules),sort_keys=True,indent=2)+'\n'
    release=target.parent/'release.json'
    if check:
        if not release.exists() or release.read_text()!=manifest:
            print("DEBUG release target_match=False expected_manifest="+manifest)
            raise SystemExit('Run python tools/build_ui.py to refresh the nine-module release manifest')
    else:
        release.write_text(manifest)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
